"""Puertos de salida del módulo pasajero (B6)."""

from __future__ import annotations

from datetime import datetime
from typing import Any, Protocol
from uuid import UUID

Registro = dict[str, Any]


class RepositorioFavoritos(Protocol):
    async def listar(self, usuario_id: UUID) -> list[Registro]: ...
    async def destino_existe(self, tipo: str, objetivo_id: UUID) -> bool: ...
    async def buscar(self, usuario_id: UUID, tipo: str, objetivo_id: UUID) -> Registro | None: ...
    async def crear(self, usuario_id: UUID, tipo: str, objetivo_id: UUID) -> Registro: ...
    async def eliminar(self, usuario_id: UUID, favorito_id: UUID) -> bool: ...


class RepositorioAlertas(Protocol):
    async def paradero_en_ruta_activa(self, ruta_id: UUID, paradero_id: UUID) -> bool: ...
    async def listar(self, usuario_id: UUID) -> list[Registro]: ...
    async def crear(
        self, usuario_id: UUID | None, telegram_chat_id: int | None, ruta_id: UUID, paradero_id: UUID, distancia_m: int
    ) -> Registro:
        """ErrorConflictoNegocio si ya hay una alerta activa igual (índices únicos parciales)."""
        ...
    async def desactivar(self, usuario_id: UUID, alerta_id: UUID) -> bool: ...
    async def activas_de_ruta(self, ruta_id: UUID) -> list[Registro]:
        """Alertas no desactivadas de la ruta: id, usuario_id, telegram_chat_id, paradero_id, distancia_aviso_m,
        ultima_notificacion_en, ruta_id."""
        ...
    async def marcar_notificada(self, alerta_id: UUID, cuando: datetime) -> None: ...


class RepositorioProgreso(Protocol):
    async def progreso_de_punto(self, ruta_id: UUID, lat: float, lng: float) -> Registro | None:
        """progreso_m, desvio_m y longitud_m de un punto sobre el trazado circular."""
        ...
    async def progreso_paradero(self, ruta_id: UUID, paradero_id: UUID) -> Registro | None: ...
