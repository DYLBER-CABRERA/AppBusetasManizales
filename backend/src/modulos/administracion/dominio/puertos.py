"""Puertos de salida del módulo administración (B3b: perfil, autenticación y demo)."""

from __future__ import annotations

from typing import Any, Protocol
from uuid import UUID


class RepositorioUsuarios(Protocol):
    async def perfil(self, usuario_id: UUID) -> dict[str, Any] | None:
        """usuario_id, correo, rol, empresa_id, empresa_nombre, activo; None si no hay perfil."""
        ...


class PuertoSimulador(Protocol):
    """Lo que el panel de demo necesita del simulador de GPS (herramientas/simulador_gps.py)."""

    async def aplicar(self, escenario: dict[str, Any]) -> None: ...

    def estado(self) -> dict[str, Any]: ...


class PuertoAltaUsuarios(Protocol):
    async def crear_usuario(self, correo: str, nombre: str | None) -> UUID:
        """Crea la cuenta en Supabase Auth (invitación por correo) y devuelve su id."""
        ...


class RepositorioAdmin(Protocol):
    # usuarios
    async def listar_usuarios(self, correo: str | None) -> list[dict[str, Any]]: ...
    async def obtener_usuario(self, usuario_id: UUID) -> dict[str, Any] | None: ...
    async def correo_existe(self, correo: str) -> bool: ...
    async def crear_perfil(
        self, usuario_id: UUID, correo: str, nombre: str | None, rol: str, empresa_id: UUID | None
    ) -> dict[str, Any]: ...
    async def editar_usuario(
        self, usuario_id: UUID, version: int, nombre: str | None, rol: str, empresa_id: UUID | None, activo: bool
    ) -> dict[str, Any]: ...
    async def contar_administradores_activos(self) -> int: ...
    # empresas
    async def empresa_activa(self, empresa_id: UUID) -> bool: ...
    async def listar_empresas(self) -> list[dict[str, Any]]: ...
    async def crear_empresa(self, nombre: str) -> dict[str, Any]: ...
    async def editar_empresa(self, empresa_id: UUID, version: int, nombre: str | None, estado: str | None) -> dict[str, Any]: ...
    # credenciales GPS
    async def listar_credenciales(self, empresa_id: UUID) -> list[dict[str, Any]]: ...
    async def crear_credencial(self, empresa_id: UUID, nombre: str, hash_clave: str) -> dict[str, Any]: ...
    async def revocar_credencial(self, credencial_id: UUID) -> bool: ...
    # parámetros
    async def listar_parametros(self) -> list[dict[str, Any]]: ...
    async def obtener_parametro(self, clave: str) -> dict[str, Any] | None: ...
    async def actualizar_parametro(self, clave: str, valor: Any, version: int) -> dict[str, Any]: ...
