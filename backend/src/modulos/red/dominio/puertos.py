"""Puertos de salida del módulo red (consulta pública, B2). Los repositorios devuelven dicts en snake_case."""

from __future__ import annotations

from datetime import date, datetime
from typing import Any, Protocol
from uuid import UUID

Registro = dict[str, Any]


class RepositorioRutas(Protocol):
    async def rutas_cercanas(self, lat: float, lng: float, radio_m: int) -> list[Registro]:
        """Rutas activas con servicios; cada dict trae `distancia_m`. Orden: más cercana primero."""
        ...

    async def listar_activas(self) -> list[Registro]: ...

    async def resumenes(self, ruta_ids: list[UUID], distancias: dict[UUID, float] | None = None) -> list[Registro]:
        """Resumen (con servicios) de las rutas activas indicadas, en el mismo orden."""
        ...

    async def obtener_detalle(self, ruta_id: UUID) -> Registro | None:
        """Ruta activa con trazado GeoJSON, paraderos ordenados y servicios; None si no existe o está de baja."""
        ...

    async def paraderos_cercanos(self, lat: float, lng: float, radio_m: int, ruta_id: UUID | None) -> list[Registro]: ...

    async def paradero_mas_cercano(self, lat: float, lng: float) -> Registro | None: ...

    async def listar_empresas(self) -> list[Registro]: ...


Coordenada = tuple[float, float]  # (lat, lng)


class EnrutadorCalles(Protocol):
    async def trazar(self, origen: Coordenada, destino: Coordenada) -> list[Coordenada] | None:
        """Geometría por calles reales entre dos puntos (lista de (lat, lng) con ≥ 2 vértices), o `None` si no hay ruta
        real (sin respuesta, error o «NoRoute»). Nunca lanza: quien llama usa una recta de respaldo."""
        ...


class ProveedorAvisosVigentes(Protocol):
    async def vigentes(self, ruta_id: UUID | None, ahora: datetime) -> list[Registro]: ...


class RepositorioGestionRed(Protocol):
    """Escritura de la red por la Secretaría (B5). Las bajas son lógicas; toda escritura lleva `version`."""

    async def listar_paraderos(self) -> list[Registro]: ...
    async def obtener_paradero(self, paradero_id: UUID) -> Registro | None: ...
    async def hay_paradero_duplicado(self, nombre: str, lat: float, lng: float, excluir_id: UUID | None) -> bool: ...
    async def crear_paradero(self, nombre: str, direccion: str | None, lat: float, lng: float) -> Registro: ...
    async def editar_paradero(
        self, paradero_id: UUID, version: int, nombre: str, direccion: str | None, lat: float, lng: float
    ) -> Registro: ...
    async def rutas_que_usan_paradero(self, paradero_id: UUID) -> list[Registro]: ...
    async def dar_de_baja_paradero(self, paradero_id: UUID, version: int) -> None: ...
    async def crear_hito(self, nombre: str, tipo: str, alias: list[str], lat: float, lng: float) -> Registro: ...

    async def paraderos_activos_existen(self, paradero_ids: list[UUID]) -> bool: ...
    async def empresas_activas_existen(self, empresa_ids: list[UUID]) -> bool: ...
    async def ruta_principal_valida(self, ruta_id: UUID) -> bool: ...
    async def crear_ruta(
        self, nombre: str, ruta_principal_id: UUID | None, paradero_ids: list[UUID], servicios: list[Registro]
    ) -> UUID: ...
    async def editar_ruta(
        self, ruta_id: UUID, version: int, nombre: str | None, descripcion: str | None, paradero_ids: list[UUID] | None
    ) -> None: ...
    async def turnos_futuros_de_ruta(self, ruta_id: UUID, desde: date) -> list[Registro]: ...
    async def dar_de_baja_ruta(self, ruta_id: UUID, version: int) -> None: ...

    async def ruta_nombre_existe(self, nombre: str) -> bool:
        """¿Hay una ruta activa con ese nombre (sin tildes ni mayúsculas)?"""
        ...
    async def paradero_cercano(self, lat: float, lng: float, radio_m: float, excluir_ids: list[UUID]) -> Registro | None:
        """Paradero activo más cercano a ≤ radio_m (id, nombre, lat, lng, distancia_m) que no esté en `excluir_ids`."""
        ...
    async def crear_ruta_con_paraderos(
        self, nombre: str, ruta_principal_id: UUID | None, paraderos: list[Registro], servicios: list[Registro],
        trazado: list[Coordenada] | None = None,
    ) -> UUID:
        """UNA transacción: crea los paraderos con `id` None (nombre, lat, lng, direccion), la ruta circular con su trazado
        (`trazado` = vértices (lat, lng) ya cerrados; si falta, una recta entre paraderos que vuelve al primero), la secuencia
        de paradas y los servicios. Si algo falla no queda nada."""
        ...
    async def ruta_activa_existe(self, ruta_id: UUID) -> bool: ...
    async def empresa_opera_ruta(self, ruta_id: UUID, empresa_id: UUID) -> bool: ...
    async def empresas_que_operan_ruta(self, ruta_id: UUID) -> list[UUID]: ...
    async def asignar_servicio(
        self, ruta_id: UUID, empresa_id: UUID, codigo_publico: str | None, codigo_interno: str | None
    ) -> Registro: ...
    async def obtener_servicio(self, servicio_id: UUID) -> Registro | None: ...
    async def turnos_futuros_de_servicio(self, servicio_id: UUID, desde: date) -> list[Registro]: ...
    async def retirar_servicio(self, servicio_id: UUID, version: int, hoy: date) -> None: ...
